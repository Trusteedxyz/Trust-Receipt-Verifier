/**
 * Embedded Issuer Root Certificate(s) — pinned trust anchor for offline
 * verification of TrustReceipt bundles + receipts.
 *
 * Consumers of `trust-receipt-verifier` use the active
 * embedded root as the trust anchor when validating the signed JWKS history
 * shipped alongside an export bundle. This avoids dependence on a live
 * `.well-known/jwks.json` fetch at verify time.
 *
 * Root rotation = SemVer bump of the verifier package: a new entry is
 * prepended to {@link EMBEDDED_ISSUER_ROOTS} (newest first) and the
 * previously-active entry's `validTo` is set to its retirement timestamp.
 *
 * Production root
 * ===============
 * The active entry is the self-signed Ed25519 root generated by the offline
 * key ceremony. The previous staging stub is no longer embedded; only its
 * fingerprint survives, as `_STAGING_STUB_ROOT_SHA256`, so that the stub can
 * still be RECOGNISED and rejected wherever it shows up (an old bundle, a
 * stale build).
 *
 * Two constants, two meanings: never merge them.
 *   - `_ISSUER_ROOT_SHA256`        the root this package trusts.
 *   - `_STAGING_STUB_ROOT_SHA256`  the root this package must NEVER trust.
 *     It is a detector only: writing the production fingerprint there would
 *     make the real root classify as a stub.
 */

/**
 * One embedded root cert entry. Either currently active (`validTo === null`)
 * or retired (`validTo` set to the retirement instant in Unix seconds).
 */
export interface IssuerRootEntry {
  /** Self-signed Ed25519 cert (PEM-encoded). */
  readonly pem: string;
  /** SHA-256 of the PEM bytes (UTF-8), lowercase hex. */
  readonly sha256: string;
  /** Unix seconds — minimum issuance time this root may sign for. */
  readonly validFrom: number;
  /** Unix seconds — `null` if currently active (no expiry yet). */
  readonly validTo: number | null;
  /** Verifier-package SemVer that introduces this root entry. */
  readonly verifierMinVersion: string;
}

